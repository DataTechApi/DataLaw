-- -----------------------------------------------------------------------------
-- gold — facts
-- -----------------------------------------------------------------------------

CREATE TABLE gold.fact_processo (
    processo_sk                  BIGINT PRIMARY KEY,
    id_datajud                   TEXT        NOT NULL,
    numero_processo              TEXT        NOT NULL,
    tribunal_sigla               TEXT        NOT NULL
        REFERENCES gold.dim_tribunal (sigla),
    grau                         TEXT        NOT NULL
        REFERENCES gold.dim_grau (codigo),
    classe_codigo                INTEGER     NOT NULL
        REFERENCES gold.dim_classe (codigo),
    orgao_codigo                 INTEGER     NOT NULL
        REFERENCES gold.dim_orgao_julgador (codigo),
    formato_codigo               INTEGER     NOT NULL
        REFERENCES gold.dim_formato (codigo),
    sistema_codigo               INTEGER     NOT NULL
        REFERENCES gold.dim_sistema (codigo),
    data_ajuizamento_key         INTEGER     NOT NULL
        REFERENCES gold.dim_tempo (date_key),
    data_baixa_key               INTEGER
        REFERENCES gold.dim_tempo (date_key),
    data_ultimo_movimento_key    INTEGER
        REFERENCES gold.dim_tempo (date_key),
    data_ajuizamento             TIMESTAMPTZ NOT NULL,
    data_evento_terminal         TIMESTAMPTZ,
    qtd_movimentos               INTEGER     NOT NULL CHECK (qtd_movimentos >= 0),
    qtd_assuntos                 INTEGER     NOT NULL CHECK (qtd_assuntos >= 0),
    duracao_dias                 INTEGER     CHECK (duracao_dias IS NULL OR duracao_dias >= 0),
    tem_baixa_definitiva         BOOLEAN     NOT NULL DEFAULT FALSE,
    tem_arquivamento_definitivo  BOOLEAN     NOT NULL DEFAULT FALSE,
    fonte                        TEXT        NOT NULL DEFAULT 'DataJud/CNJ',
    confiabilidade_score         NUMERIC(5, 4)
        CHECK (
            confiabilidade_score IS NULL
            OR (confiabilidade_score >= 0 AND confiabilidade_score <= 1)
        ),
    confiabilidade_motivo        TEXT,
    aderente_flag                BOOLEAN,
    resultado_codigo             TEXT,
    loaded_at                    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_fact_processo_id UNIQUE (id_datajud)
);

COMMENT ON TABLE  gold.fact_processo IS
    'Grain: one process. Volume, duration, terminal-movement flags, source/reliability.';
COMMENT ON COLUMN gold.fact_processo.processo_sk IS
    'Copied from silver.processo.processo_sk. Not a FK so gold can be rebuilt independently.';
COMMENT ON COLUMN gold.fact_processo.data_evento_terminal IS
    'dataHora of the first movement 22 or 246. Duration = this - data_ajuizamento.';
COMMENT ON COLUMN gold.fact_processo.tem_baixa_definitiva IS
    'Exists TPU 22 (Baixa Definitiva).';
COMMENT ON COLUMN gold.fact_processo.tem_arquivamento_definitivo IS
    'Exists TPU 246 (Definitivo).';
COMMENT ON COLUMN gold.fact_processo.fonte IS
    'Sprint 1.5 source label. Always DataJud/CNJ for this pipeline.';
COMMENT ON COLUMN gold.fact_processo.confiabilidade_score IS
    'ETL-derived 0-1 from sigilo, presenca de assuntos/movimentos, and freshness.';
COMMENT ON COLUMN gold.fact_processo.aderente_flag IS
    'Reserved. Null until the adherence business rule is confirmed.';
COMMENT ON COLUMN gold.fact_processo.resultado_codigo IS
    'Reserved outcome code. Null until classification exists.';

CREATE INDEX ix_fact_processo_tribunal_ajuiz
    ON gold.fact_processo (tribunal_sigla, data_ajuizamento_key);
CREATE INDEX ix_fact_processo_classe
    ON gold.fact_processo (classe_codigo);
CREATE INDEX ix_fact_processo_orgao
    ON gold.fact_processo (orgao_codigo);
CREATE INDEX ix_fact_processo_baixa
    ON gold.fact_processo (data_baixa_key);
CREATE INDEX ix_fact_processo_numero
    ON gold.fact_processo (numero_processo);

CREATE TABLE gold.fact_movimento (
    movimento_sk          BIGINT PRIMARY KEY,
    processo_sk           BIGINT      NOT NULL
        REFERENCES gold.fact_processo (processo_sk) ON DELETE CASCADE,
    tipo_movimento_codigo INTEGER     NOT NULL
        REFERENCES gold.dim_tipo_movimento (codigo),
    orgao_codigo          INTEGER     NOT NULL
        REFERENCES gold.dim_orgao_julgador (codigo),
    data_key              INTEGER     NOT NULL
        REFERENCES gold.dim_tempo (date_key),
    data_hora             TIMESTAMPTZ NOT NULL,
    nome                  TEXT,
    ordem_origem          INTEGER     NOT NULL CHECK (ordem_origem >= 0),
    tem_complementos      BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_fact_movimento_carga UNIQUE (processo_sk, ordem_origem)
);

COMMENT ON TABLE gold.fact_movimento IS
    'Grain: one movement event. Use for processing-time paths and movement mix.';

CREATE INDEX ix_fact_movimento_processo
    ON gold.fact_movimento (processo_sk);
CREATE INDEX ix_fact_movimento_tipo_data
    ON gold.fact_movimento (tipo_movimento_codigo, data_key);
CREATE INDEX ix_fact_movimento_orgao
    ON gold.fact_movimento (orgao_codigo);

CREATE TABLE gold.bridge_processo_assunto (
    processo_sk    BIGINT  NOT NULL
        REFERENCES gold.fact_processo (processo_sk) ON DELETE CASCADE,
    assunto_codigo INTEGER NOT NULL
        REFERENCES gold.dim_assunto (codigo),
    PRIMARY KEY (processo_sk, assunto_codigo)
);

COMMENT ON TABLE gold.bridge_processo_assunto IS
    'M:N bridge. Topic filter uses TPU assunto until NLP classification exists.';

CREATE INDEX ix_bridge_processo_assunto_assunto
    ON gold.bridge_processo_assunto (assunto_codigo);

