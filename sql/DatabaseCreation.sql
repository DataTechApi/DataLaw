BEGIN;

CREATE SCHEMA IF NOT EXISTS bronze;
CREATE SCHEMA IF NOT EXISTS silver;
CREATE SCHEMA IF NOT EXISTS gold;

COMMENT ON SCHEMA bronze IS 'Bronze: raw DataJud extracts. Append-only.';
COMMENT ON SCHEMA silver IS 'Silver: conformed process/movement model.';
COMMENT ON SCHEMA gold   IS 'Gold: dimensional star for Sprint 1 indicators.';

-- -----------------------------------------------------------------------------
-- bronze
-- -----------------------------------------------------------------------------

CREATE TABLE bronze.datajud_extract (
    extract_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tribunal_alias  TEXT        NOT NULL,
    tribunal_sigla  TEXT        NOT NULL,
    source_file     TEXT        NOT NULL,
    extracted_at    TIMESTAMPTZ NOT NULL,
    took_ms         INTEGER,
    timed_out       BOOLEAN,
    shards          JSONB,
    hit_count       INTEGER     NOT NULL CHECK (hit_count >= 0),
    payload         JSONB       NOT NULL,
    CONSTRAINT uq_datajud_extract_source_file UNIQUE (source_file)
);

COMMENT ON TABLE  bronze.datajud_extract IS
    'One row per ingestion file. payload is the full Elasticsearch response.';
COMMENT ON COLUMN bronze.datajud_extract.tribunal_alias IS
    'Path segment used in the API, e.g. api_publica_tjsp.';
COMMENT ON COLUMN bronze.datajud_extract.tribunal_sigla IS
    'Directory/sigla used by save_raw_response, e.g. tjsp -> TJSP.';
COMMENT ON COLUMN bronze.datajud_extract.payload IS
    'Raw JSON: took, timed_out, _shards, hits.';

CREATE TABLE bronze.datajud_hit (
    hit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extract_id BIGINT NOT NULL
        REFERENCES bronze.datajud_extract (extract_id) ON DELETE CASCADE,
    es_index   TEXT    NOT NULL,
    es_id      TEXT    NOT NULL,
    es_score   NUMERIC,
    source     JSONB   NOT NULL,
    CONSTRAINT uq_datajud_hit_extract_es UNIQUE (extract_id, es_id)
);

COMMENT ON TABLE  bronze.datajud_hit IS
    'One row per hits.hits[] element. source is _source, still nested.';
COMMENT ON COLUMN bronze.datajud_hit.es_id IS
    'Elasticsearch _id. In this TJSP extract it equals _source.id.';
COMMENT ON COLUMN bronze.datajud_hit.source IS
    'Unparsed _source: capa + assuntos[] + movimentos[].';

CREATE INDEX ix_datajud_hit_extract_id ON bronze.datajud_hit (extract_id);
CREATE INDEX ix_datajud_hit_es_id      ON bronze.datajud_hit (es_id);

-- -----------------------------------------------------------------------------
-- silver — reference / TPU
-- -----------------------------------------------------------------------------

CREATE TABLE silver.tribunal (
    sigla TEXT PRIMARY KEY,
    nome  TEXT NOT NULL
);

CREATE TABLE silver.grau (
    codigo    TEXT PRIMARY KEY,
    descricao TEXT NOT NULL
);

CREATE TABLE silver.formato (
    codigo INTEGER PRIMARY KEY,
    nome   TEXT NOT NULL
);

CREATE TABLE silver.sistema (
    codigo INTEGER PRIMARY KEY,
    nome   TEXT NOT NULL
);

CREATE TABLE silver.classe_processual (
    codigo INTEGER PRIMARY KEY,
    nome   TEXT NOT NULL
);

COMMENT ON TABLE silver.classe_processual IS
    'TPU processual class. Business key = classe.codigo.';

CREATE TABLE silver.assunto (
    codigo INTEGER PRIMARY KEY,
    nome   TEXT NOT NULL
);

COMMENT ON TABLE silver.assunto IS
    'TPU subject. Business key = assuntos[].codigo. NLP topic is a later column.';

CREATE TABLE silver.orgao_julgador (
    codigo                INTEGER PRIMARY KEY,
    nome                  TEXT    NOT NULL,
    codigo_municipio_ibge INTEGER,
    tribunal_sigla        TEXT    NOT NULL
        REFERENCES silver.tribunal (sigla)
);

COMMENT ON TABLE silver.orgao_julgador IS
    'CNJ organ/serventia. IBGE is present on the capa and often absent on the movement.';
COMMENT ON COLUMN silver.orgao_julgador.codigo IS
    'orgaoJulgador.codigo (int) / movimentos.orgaoJulgador.codigo (string -> int).';

CREATE INDEX ix_orgao_julgador_tribunal ON silver.orgao_julgador (tribunal_sigla);
CREATE INDEX ix_orgao_julgador_ibge     ON silver.orgao_julgador (codigo_municipio_ibge);

CREATE TABLE silver.tipo_movimento (
    codigo INTEGER PRIMARY KEY,
    nome   TEXT
);

COMMENT ON TABLE  silver.tipo_movimento IS
    'TPU movement type. nome is nullable because the source omits it on some codes.';
COMMENT ON COLUMN silver.tipo_movimento.nome IS
    'Last-seen movimentos.nome for this codigo. Event-level name lives on silver.movimento.';

CREATE TABLE silver.tipo_complemento (
    codigo    INTEGER PRIMARY KEY,
    descricao TEXT    NOT NULL
);

COMMENT ON TABLE silver.tipo_complemento IS
    'Tabulated complement variable, e.g. codigo 3 / descricao tipo_de_conclusao.';

CREATE TABLE silver.valor_complemento (
    tipo_complemento_codigo INTEGER NOT NULL
        REFERENCES silver.tipo_complemento (codigo),
    valor                   INTEGER NOT NULL,
    nome                    TEXT    NOT NULL,
    PRIMARY KEY (tipo_complemento_codigo, valor)
);

COMMENT ON TABLE silver.valor_complemento IS
    'Conformed label for a complement value, e.g. valor 36 = para julgamento.';

-- -----------------------------------------------------------------------------
-- silver — process grain
-- -----------------------------------------------------------------------------

CREATE TABLE silver.processo (
    processo_sk                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_datajud                    TEXT        NOT NULL,
    numero_processo               TEXT        NOT NULL,
    tribunal_sigla                TEXT        NOT NULL
        REFERENCES silver.tribunal (sigla),
    grau                          TEXT        NOT NULL
        REFERENCES silver.grau (codigo),
    classe_codigo                 INTEGER     NOT NULL
        REFERENCES silver.classe_processual (codigo),
    sistema_codigo                INTEGER     NOT NULL
        REFERENCES silver.sistema (codigo),
    formato_codigo                INTEGER     NOT NULL
        REFERENCES silver.formato (codigo),
    orgao_julgador_codigo         INTEGER     NOT NULL
        REFERENCES silver.orgao_julgador (codigo),
    nivel_sigilo                  INTEGER     NOT NULL DEFAULT 0
        CHECK (nivel_sigilo >= 0),
    data_ajuizamento              TIMESTAMPTZ NOT NULL,
    data_hora_ultima_atualizacao  TIMESTAMPTZ,
    source_extract_id             BIGINT
        REFERENCES bronze.datajud_extract (extract_id) ON DELETE SET NULL,
    ingested_at                   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_processo_id_datajud UNIQUE (id_datajud),
    CONSTRAINT uq_processo_natural    UNIQUE (tribunal_sigla, grau, numero_processo)
);

COMMENT ON TABLE  silver.processo IS
    'One DataJud document. Natural key (tribunal, grau, numero_processo).';
COMMENT ON COLUMN silver.processo.id_datajud IS
    '_source.id. Opaque business key — do not parse.';
COMMENT ON COLUMN silver.processo.numero_processo IS
    'CNJ number, unformatted. TEXT to preserve leading zeros.';
COMMENT ON COLUMN silver.processo.data_ajuizamento IS
    'Parsed from compact YYYYMMDDHHMMSS or ISO-8601.';
COMMENT ON COLUMN silver.processo.orgao_julgador_codigo IS
    'Cover organ (current). Movement organs may differ; see silver.movimento.';

CREATE INDEX ix_processo_tribunal_ajuizamento
    ON silver.processo (tribunal_sigla, data_ajuizamento);
CREATE INDEX ix_processo_classe
    ON silver.processo (classe_codigo);
CREATE INDEX ix_processo_orgao
    ON silver.processo (orgao_julgador_codigo);
CREATE INDEX ix_processo_numero
    ON silver.processo (numero_processo);
CREATE INDEX ix_processo_extract
    ON silver.processo (source_extract_id);

CREATE TABLE silver.processo_assunto (
    processo_sk    BIGINT  NOT NULL
        REFERENCES silver.processo (processo_sk) ON DELETE CASCADE,
    assunto_codigo INTEGER NOT NULL
        REFERENCES silver.assunto (codigo),
    PRIMARY KEY (processo_sk, assunto_codigo)
);

COMMENT ON TABLE silver.processo_assunto IS
    'M:N process x TPU assunto. Replace-on-reload with the parent process.';

CREATE INDEX ix_processo_assunto_assunto ON silver.processo_assunto (assunto_codigo);

-- -----------------------------------------------------------------------------
-- silver — movement grain (synthesized; source has no movement id)
-- -----------------------------------------------------------------------------

CREATE TABLE silver.movimento (
    movimento_sk          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_sk           BIGINT      NOT NULL
        REFERENCES silver.processo (processo_sk) ON DELETE CASCADE,
    tipo_movimento_codigo INTEGER     NOT NULL
        REFERENCES silver.tipo_movimento (codigo),
    data_hora             TIMESTAMPTZ NOT NULL,
    orgao_julgador_codigo INTEGER     NOT NULL
        REFERENCES silver.orgao_julgador (codigo),
    nome_origem           TEXT,
    ordem_origem          INTEGER     NOT NULL
        CHECK (ordem_origem >= 0),
    CONSTRAINT uq_movimento_carga UNIQUE (processo_sk, ordem_origem)
);

COMMENT ON TABLE  silver.movimento IS
    'Unnested movimentos[]. Surrogate PK: the API does not emit a movement id.';
COMMENT ON COLUMN silver.movimento.ordem_origem IS
    '0-based index in the JSON array. Load-time discriminator only — not time.';
COMMENT ON COLUMN silver.movimento.nome_origem IS
    'movimentos.nome as received; null when the field is omitted.';
COMMENT ON COLUMN silver.movimento.orgao_julgador_codigo IS
    'Organ of the event. Differed from the cover organ on 334/5792 rows in the extract.';

CREATE INDEX ix_movimento_processo
    ON silver.movimento (processo_sk);
CREATE INDEX ix_movimento_tipo_data
    ON silver.movimento (tipo_movimento_codigo, data_hora);
CREATE INDEX ix_movimento_orgao
    ON silver.movimento (orgao_julgador_codigo);
CREATE INDEX ix_movimento_data_hora
    ON silver.movimento (data_hora);

CREATE TABLE silver.movimento_complemento (
    movimento_sk            BIGINT  NOT NULL
        REFERENCES silver.movimento (movimento_sk) ON DELETE CASCADE,
    tipo_complemento_codigo INTEGER NOT NULL,
    valor                   INTEGER NOT NULL,
    nome_origem             TEXT    NOT NULL,
    PRIMARY KEY (movimento_sk, tipo_complemento_codigo, valor),
    CONSTRAINT fk_mov_comp_valor
        FOREIGN KEY (tipo_complemento_codigo, valor)
        REFERENCES silver.valor_complemento (tipo_complemento_codigo, valor)
);

COMMENT ON TABLE silver.movimento_complemento IS
    'Unnested movimentos[].complementosTabelados[]. Snapshot name on nome_origem.';

CREATE INDEX ix_movimento_complemento_tipo
    ON silver.movimento_complemento (tipo_complemento_codigo, valor);

